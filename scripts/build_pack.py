#!/usr/bin/env python3
"""Build a pack library: every action of one pack linked into one native library.

Apps that bundle actions (Android and iOS) ship one pack library per pack
instead of one library per action. See core_types/src/pack.rs.

    python3 scripts/build_pack.py base --out dist/
    python3 scripts/build_pack.py audio_basics --target aarch64-linux-android --out dist/

The pack crate is generated under target/packs/<pack>/ as its own workspace,
with the repository's Cargo.lock so dependency versions match the actions'
regular builds. Actions are compiled with `--cfg morflow_pack`, which drops
their individual exported symbols so they can be linked together.
"""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from detect_changed_actions import discover_all_actions  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# Packs whose actions need a plugin cannot be bundled.
PLUGIN_PACKS = {"image_opencv", "linalg_blas", "tensor_blas"}


def library_file(stem: str, target: str | None) -> str:
    triple = target or host_triple()
    if "windows" in triple:
        return f"{stem}.dll"
    if "apple" in triple:
        return f"lib{stem}.dylib"
    return f"lib{stem}.so"


def host_triple() -> str:
    output = subprocess.run(["rustc", "-vV"], capture_output=True, text=True, check=True).stdout
    return next(line.split(": ", 1)[1] for line in output.splitlines() if line.startswith("host: "))


def pack_actions(pack: str) -> list[dict]:
    actions = [a for a in discover_all_actions(ROOT) if a["pack"] == pack]
    if not actions:
        raise SystemExit(f"Unknown action pack: {pack}")
    if pack in PLUGIN_PACKS or any(a.get("plugins") for a in actions):
        raise SystemExit(f"{pack} needs a plugin and cannot be built as a pack library")
    versions = {a["version"] for a in actions}
    if len(versions) != 1:
        raise SystemExit(f"{pack} actions have different versions: {', '.join(sorted(versions))}")
    return actions


def generate(pack: str, actions: list[dict]) -> Path:
    crate = ROOT / "target" / "packs" / pack
    crate.mkdir(parents=True, exist_ok=True)
    version = actions[0]["version"]
    # Each action is aliased, since action names such as `std` would shadow
    # Rust's own crates.
    dependencies = "\n".join(
        f'action_{a["library"]} = {{ package = "{a["package"]}", path = "{(ROOT / a["path"]).as_posix()}" }}'
        for a in actions
    )
    (crate / "Cargo.toml").write_text(f'''# Generated by scripts/build_pack.py. Do not edit.
[package]
name = "morflow_pack_{pack}"
version = "{version}"
edition = "2021"
publish = false

[lib]
path = "lib.rs"
crate-type = ["cdylib"]

[dependencies]
core_types = {{ package = "morflow-core-types", path = "{(ROOT / "core_types").as_posix()}" }}
{dependencies}

[profile.release]
lto = "fat"
codegen-units = 1
strip = "symbols"

# A standalone workspace, so the pack is never part of a regular build.
[workspace]
''')
    entries = ",\n        ".join(f'"{a["name"]}" => action_{a["library"]}' for a in actions)
    (crate / "lib.rs").write_text(f'''// Generated by scripts/build_pack.py. Do not edit.
core_types::morflow_pack! {{
    pack: "{pack}",
    version: "{version}",
    actions: [
        {entries},
    ],
}}
''')
    shutil.copyfile(ROOT / "Cargo.lock", crate / "Cargo.lock")
    return crate


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("pack")
    parser.add_argument("--target", help="Rust target triple (default: the host)")
    parser.add_argument("--out", type=Path, required=True, help="Directory to copy the library into")
    args = parser.parse_args()

    actions = pack_actions(args.pack)
    crate = generate(args.pack, actions)
    target_dir = ROOT / "target" / "packs-build"
    command = ["cargo", "build", "--release", "--manifest-path", str(crate / "Cargo.toml"),
               "--target-dir", str(target_dir)]
    if args.target:
        command += ["--target", args.target]
    env = dict(os.environ)
    env["RUSTFLAGS"] = (env.get("RUSTFLAGS", "") + " --cfg morflow_pack").strip()
    subprocess.run(command, env=env, check=True)

    name = library_file(f"morflow_pack_{args.pack}", args.target)
    built = target_dir / (args.target or "") / "release" / name
    args.out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(built, args.out / name)
    print(f"{args.out / name} ({(args.out / name).stat().st_size} bytes, {len(actions)} actions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
